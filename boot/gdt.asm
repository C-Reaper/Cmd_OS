; ============================================================================
; PongOS
; Global Descriptor Table (GDT)
; ============================================================================

BITS 32

global gdt64
global gdt64_pointer

section .rodata
align 8

gdt64:

; ---------------------------------------------------------------------------
; Null Descriptor
; ---------------------------------------------------------------------------

dq 0x0000000000000000

; ---------------------------------------------------------------------------
; 64-bit Kernel Code Segment
;
; Access Byte:
;   Present      = 1
;   Ring         = 0
;   Code/Data    = 1
;   Executable   = 1
;   Readable     = 1
;
; Flags:
;   G = 1
;   L = 1 (64-bit)
;   D = 0
; ---------------------------------------------------------------------------

dq 0x00AF9A000000FFFF

; ---------------------------------------------------------------------------
; 64-bit Kernel Data Segment
;
; Access Byte:
;   Present      = 1
;   Ring         = 0
;   Data Segment = 1
;   Writable     = 1
; ---------------------------------------------------------------------------

dq 0x00AF92000000FFFF

gdt64_end:

; ---------------------------------------------------------------------------
; GDTR Structure
; ---------------------------------------------------------------------------

gdt64_pointer:

    dw gdt64_end - gdt64 - 1
    dd gdt64